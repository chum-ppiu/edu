const savedLocale = typeof localStorage !== 'undefined' ? localStorage.getItem(STORAGE_KEY) : null
const preferredLocale = typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('km') ? 'km' : 'en'
const locale = savedLocale || preferredLocale

const i18n = createI18n({
  legacy: false,
  locale,
  fallbackLocale: 'en',
  messages,
})

export function persistLocale(nextLocale) {
  if (typeof localStorage !== 'undefined') {
    localStorage.setItem(STORAGE_KEY, nextLocale)
  }

  i18n.global.locale.value = nextLocale
}

export function getLocale() {
  return i18n.global.locale.value
}

const applyLocaleToDocument = (locale) => {
  const htmlEl = document.documentElement;
  htmlEl.setAttribute('lang', locale);
  htmlEl.setAttribute('data-locale', locale);
};

applyLocaleToDocument(savedLocale);
watch(
  () => i18n.global.locale.value,
  (newLocale) => {
    if (!newLocale) return;
    applyLocaleToDocument(newLocale);
  }
);
export default i18n